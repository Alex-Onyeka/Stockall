// A4 report PDF: shop header, title, info box, then each section as a
// band with a bordered table (or a figures table for summaries).

import 'dart:math' as math;
import 'dart:typed_data';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:stockall/pages/report/components/export/report_document_parts.dart';
import 'package:stockall/pages/report/components/export/report_export_format.dart';
import 'package:stockall/pages/report/components/export/report_export_resolve.dart';
import 'package:stockall/pages/report/components/export/report_export_spec.dart';

/// MultiPage stops at 20 pages by default and throws. Reports can be long.
const int reportPdfMaxPages = 2000;

/// Above this many PDF columns the page turns landscape.
const int reportPdfPortraitMaxColumns = 8;

/// Up to this many columns keep the full body size.
const int reportPdfFullSizeMaxColumns = 10;

bool reportPdfLandscape(int columnCount) =>
    columnCount > reportPdfPortraitMaxColumns;

/// Body font size for a table with [columnCount] PDF columns: full size
/// up to 10 columns, then 0.25pt smaller per extra column, never below
/// the style's minimum.
double reportPdfBodySize(int columnCount, {DocStyle style = DocStyle.report}) {
  if (columnCount <= reportPdfFullSizeMaxColumns) return style.bodySize;
  final size =
      style.bodySize - 0.25 * (columnCount - reportPdfFullSizeMaxColumns);
  return math.max(style.minBodySize, size);
}

/// Widest table, by PDF columns.
int reportPdfMaxColumns(ResolvedExport r) {
  var widest = 0;
  for (final t in r.tables) {
    widest = math.max(widest, t.pdfColumnIndexes.length);
  }
  return widest;
}

pw.Alignment _alignment(ExportAlign a) {
  switch (a) {
    case ExportAlign.left:
      return pw.Alignment.centerLeft;
    case ExportAlign.center:
      return pw.Alignment.center;
    case ExportAlign.right:
      return pw.Alignment.centerRight;
  }
}

List<(String, String)> reportPdfInfoEntries(ResolvedExport r) {
  final m = r.meta;
  final f = ExportFormatter(currency: m.context.currencySymbol);
  return [
    ('Report', m.reportName),
    ('Period', m.periodLabel ?? 'All time'),
    ('Filters Applied', m.filtersText),
    ('Records', f.integer(m.recordCount)),
    if (m.sortedBy != null) ('Sorted By', m.sortedBy!),
    if (m.groupedBy != null) ('Grouped By', m.groupedBy!),
    if (m.notes.isNotEmpty) ('Notes', m.notes.join('\n')),
    ('Generated By', m.context.generatedBy),
    ('Generated At', f.dateTime(m.context.generatedAt)),
    if (r.hasExcelOnlyColumns)
      ('Note', 'Some columns are in the Excel export only.'),
  ];
}

/// A table row can't break across pages, so one huge cell would make the
/// PDF fail. Cells are cut to this many characters in the PDF; Excel
/// keeps the full text.
const int reportPdfCellMaxChars = 300;

String reportPdfCellText(String text) {
  if (text.length <= reportPdfCellMaxChars) return text;
  return '${text.substring(0, reportPdfCellMaxChars - 1).trimRight()}…';
}

/// The PDF as widgets, for tests that inspect the page setup. Call
/// `save()` on the result to get the bytes. [compress] is for tests that
/// read the page content.
pw.Document buildReportPdfDocument(
  ResolvedExport r, {
  required DocFonts fonts,
  DocStyle style = DocStyle.report,
  bool compress = true,
}) {
  final columns = reportPdfMaxColumns(r);
  final landscape = reportPdfLandscape(columns);
  final bodySize = reportPdfBodySize(columns, style: style);
  final format = landscape ? PdfPageFormat.a4.landscape : PdfPageFormat.a4;
  final generatedAt = ExportFormatter(
    currency: r.meta.context.currencySymbol,
  ).dateTime(r.meta.context.generatedAt);

  final doc = pw.Document(
    title: r.meta.reportName,
    author: r.meta.context.shopName,
    compress: compress,
  );

  doc.addPage(
    pw.MultiPage(
      pageTheme: docPageTheme(
        style,
        format: format,
        margin: pw.EdgeInsets.all(style.pageMargin),
        theme: pw.ThemeData.withFont(base: fonts.regular, bold: fonts.bold),
      ),
      maxPages: reportPdfMaxPages,
      footer: (context) =>
          docFooter(style, fonts, context, generatedAt: generatedAt),
      build: (context) => [
        docHeader(
          style,
          fonts,
          shopName: r.meta.context.shopName,
          details: r.meta.context.shopDetails,
        ),
        docTitle(style, fonts, r.meta.reportName),
        docInfoBox(
          style,
          fonts,
          title: 'Report Information',
          entries: reportPdfInfoEntries(r),
        ),
        for (final section in r.sections) ...[
          pw.SizedBox(height: 12),
          ..._section(section, style, fonts, bodySize),
        ],
      ],
    ),
  );
  return doc;
}

Future<Uint8List> buildReportPdf(
  ResolvedExport r, {
  required DocFonts fonts,
  DocStyle style = DocStyle.report,
}) {
  return buildReportPdfDocument(r, fonts: fonts, style: style).save();
}

List<pw.Widget> _section(
  ResolvedSection section,
  DocStyle s,
  DocFonts f,
  double bodySize,
) {
  if (section is ResolvedSummary) {
    return [docBand(s, f, section.title), _summaryTable(section, s, f, bodySize)];
  }
  if (section is ResolvedTable) {
    return [docBand(s, f, section.title), ...reportPdfTable(section, s, f, bodySize)];
  }
  return const [];
}

pw.Widget _summaryTable(
  ResolvedSummary summary,
  DocStyle s,
  DocFonts f,
  double bodySize,
) {
  final notes = summary.hasNotes;
  return docTable(
    s,
    f,
    fontSize: bodySize,
    columns: [
      const DocTableColumn(label: 'Metric', flex: 3),
      const DocTableColumn(
        label: 'Value',
        flex: 2,
        alignment: pw.Alignment.centerRight,
      ),
      if (notes) const DocTableColumn(label: 'Change', flex: 2),
    ],
    rows: [
      for (final m in summary.metrics)
        [m.label, m.text, if (notes) m.note ?? ''],
    ],
  );
}

/// The PDF columns of [t] as a bordered table, or a message box when
/// there are no rows.
List<pw.Widget> reportPdfTable(
  ResolvedTable t,
  DocStyle s,
  DocFonts f,
  double bodySize,
) {
  final indexes = t.pdfColumnIndexes;
  final columns = [
    for (final i in indexes)
      DocTableColumn(
        label: t.columns[i].label,
        flex: t.columns[i].width,
        alignment: _alignment(t.columns[i].align),
      ),
  ];

  if (t.isEmpty) {
    return [
      docTable(s, f, columns: columns, rows: const [], fontSize: bodySize),
      docMessageBox(s, f, t.emptyMessage),
    ];
  }

  List<String>? totals;
  if (t.totals != null) {
    totals = [for (final i in indexes) reportPdfCellText(t.totals![i].text)];
    // The first column carries the label, with its own total text, if
    // any, in brackets: "TOTAL (12 items)".
    if (totals.isNotEmpty) {
      totals[0] = totals.first.isEmpty
          ? t.totalsLabel
          : '${t.totalsLabel} (${totals.first})';
    }
  }

  return [
    docTable(
      s,
      f,
      fontSize: bodySize,
      columns: columns,
      rows: [
        for (final row in t.rows)
          [for (final i in indexes) reportPdfCellText(row[i].text)],
      ],
      totals: totals,
    ),
  ];
}
